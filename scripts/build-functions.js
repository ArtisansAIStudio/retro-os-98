// Builds self-contained Edge Function files (works with the Supabase CLI AND the dashboard editor).
// Source of truth: js/sim.js + supabase/src/*.ts. Run: node scripts/build-functions.js
const fs=require('fs');
const sim=fs.readFileSync('js/sim.js','utf8');
const util=fs.readFileSync('supabase/src/util.ts','utf8').replace(/^export /gm,'');
for(const n of ['start-run','submit-score']){
  const handler=fs.readFileSync(`supabase/src/${n}.ts`,'utf8').replace(/^import .*$/gm,'');
  fs.mkdirSync(`supabase/functions/${n}`,{recursive:true});
  fs.writeFileSync(`supabase/functions/${n}/index.ts`,'// @ts-nocheck\n// GENERATED by scripts/build-functions.js. Edit js/sim.js or supabase/src/*.ts, then rebuild.\n'+sim+'\n'+util+'\n'+handler);
  console.log('built',n);
}
